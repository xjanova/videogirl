/// คำตอบของเธอขึ้นต้นแบบคนตกใจหรือเปล่า · ใช่ = สะดุ้งก่อนพูด
///
/// ดูเฉพาะ**คำขึ้นต้น** ไม่หาทั้งข้อความ · "ไม่ต้องตกใจนะคะ" คือเธอกำลังปลอบ
/// ถ้าสะดุ้งตรงนั้นท่าจะตรงข้ามกับคำพูด · คำอุทานต้องตามด้วยช่องว่าง เครื่องหมาย
/// หรือจบข้อความ ไม่งั้น "ตายแล้วเกิดใหม่" กับ "oh nothing" จะพาเธอสะดุ้งเปล่า ๆ
bool startsStartled(String reply) => _cue.hasMatch(reply.trimLeft());

final RegExp _cue = RegExp(
  r'^(ว้าย+|อุ๊ย(ตาย)?|ตายแล้ว|ตายจริง|แย่แล้ว|whoa+|yikes|oh no)(ค่ะ|คะ|จ้า)?(?=$|[\s!?.,…~])',
  caseSensitive: false,
);
