/// ชื่อที่เจ้าของตั้งให้เธอ — และด่านที่กันชื่อที่ใช้ไม่ได้จริง
///
/// เจ้าของสั่งไว้ว่าชื่อต้อง "ไม่หยาบคาย ถูกต้อง ใช้ได้จริง เรียกได้จริง
/// ไม่ใช่ยาว หรือตั้งมั่ว" · แต่ละข้อเป็นด่านคนละตัวที่ปฏิเสธคนละแบบ
///
/// ## 🔴 ปฏิเสธแล้วต้องบอกว่าทำไม
///
/// ด่านที่คืนแค่ "ใช้ไม่ได้" ทำให้คนลองสุ่มไปเรื่อย ๆ แล้วเลิกไปเอง
/// [NameVerdict] จึงเป็นเหตุผลรายข้อ ไม่ใช่ bool — หน้าจอเอาไปบอกได้ตรง ๆ
/// ว่าติดตรงไหน
///
/// ## 🔴 รายการคำหยาบไม่มีวันครบ และไม่ควรทำท่าว่าครบ
///
/// ที่นี่กันคำที่พบบ่อยที่สุดเท่านั้น · การกรองคำหยาบด้วยรายการคำคือ
/// การไล่จับปลายทางซึ่งแพ้เสมอ (เว้นวรรค สลับสระ ใช้เลขแทนตัวอักษร)
/// แต่ก็ยังคุ้มที่จะมี เพราะมันกันกรณีที่คนพิมพ์เล่นแล้วชื่อนั้นจะไป
/// **โผล่ในหน้าจอสายจริงตอนเธอรับสายแทน** ซึ่งคนอื่นเห็นด้วย
library;

/// ผลของการตรวจชื่อ · ทุกค่าที่ไม่ใช่ [ok] มีข้อความอธิบายของตัวเองใน i18n
enum NameVerdict {
  ok,

  /// สั้นเกินจนเรียกไม่ติดปาก
  tooShort,

  /// ยาวเกินจนไม่มีใครเรียกจริง
  tooLong,

  /// มีตัวเลข อิโมจิ หรือเครื่องหมายปนมา
  badChars,

  /// หลายคำเกินไป — ชื่อเรียก ไม่ใช่ประโยค
  tooManyWords,

  /// ตัวอักษรซ้ำ ๆ หรือสระลอย ไม่ใช่ชื่อที่ออกเสียงได้
  notPronounceable,

  /// คำหยาบ
  rude;

  bool get isOk => this == NameVerdict.ok;
}

/// ยาวสุดที่ยังเรียกได้จริง
///
/// 16 มาจากการชั่ง: ชื่อไทยที่ยาวที่สุดที่คนเรียกกันจริง ("น้องน้ำหวาน")
/// อยู่ที่ราว 12 · เผื่อไว้อีกหน่อยแล้วตัด · ยาวกว่านี้คือคนกำลังพิมพ์เล่น
/// ไม่ใช่กำลังตั้งชื่อ
const kNameMaxChars = 16;
const kNameMinChars = 2;

/// อักษรไทย (รวมสระและวรรณยุกต์) · อักษรละติน · ช่องว่างเดียว
final _allowed = RegExp(r'^[ก-๎a-zA-ZÀ-ɏ ]+$');

/// พยัญชนะไทย และสระละติน — ชื่อต้องมีอย่างน้อยหนึ่งตัวถึงจะออกเสียงได้
final _hasBody = RegExp(r'[ก-ฮa-zA-Z]');

/// สระและวรรณยุกต์ที่ขึ้นต้นคำไม่ได้ — ขึ้นต้นด้วยตัวพวกนี้คือพิมพ์มั่ว
///
/// 🔴 **ห้ามใช้ช่วง ะ-๎ ทั้งก้อน** เพราะสระหน้า เ แ โ ใ ไ (U+0E40–U+0E44)
/// อยู่ในช่วงนั้นด้วย ทั้งที่ขึ้นต้นคำได้ตามปกติ · เคยเขียนแบบนั้นแล้ว
/// "ใบเฟิร์น" ถูกปฏิเสธว่าออกเสียงไม่ได้ — จับได้เพราะเทสต์มีชื่อไทยจริง
/// อยู่ในรายการ ไม่ใช่เพราะอ่านโค้ดแล้วเห็น
final _startsWithMark = RegExp(r'^[ะ-ฺ็-๎]');

/// คำที่กันแน่ ๆ · เก็บแบบไม่มีวรรณยุกต์เพื่อจับรูปที่เขียนต่างกันได้บ้าง
///
/// รายการนี้**ไม่ครบและไม่มีวันครบ** ดูเหตุผลในหัวไฟล์
const _rude = <String>[
  'เหี้ย', 'สัส', 'ควย', 'หี', 'เย็ด', 'แตด', 'ระยำ', 'ชาติหมา',
  'อีดอก', 'กะหรี่', 'สถุน', 'ไอ้เวร', 'มึง', 'กู',
  'fuck', 'shit', 'bitch', 'cunt', 'dick', 'pussy', 'slut', 'whore',
];

/// เก็บชื่อให้เรียบร้อยก่อนตรวจและก่อนบันทึก
///
/// ตัดหัวท้าย ยุบช่องว่างซ้ำเหลือหนึ่ง · ทำที่เดียวกันทั้งตอนตรวจและตอนเก็บ
/// ไม่งั้นจะมีชื่อที่ผ่านด่านแล้วถูกเก็บเป็นอีกแบบ แล้วเทียบกันไม่ตรง
String tidyName(String raw) => raw.trim().replaceAll(RegExp(r'\s+'), ' ');

/// ตรวจชื่อที่เจ้าของตั้งให้เธอ
NameVerdict checkName(String raw) {
  final name = tidyName(raw);

  if (name.length < kNameMinChars) return NameVerdict.tooShort;
  if (name.length > kNameMaxChars) return NameVerdict.tooLong;
  if (!_allowed.hasMatch(name)) return NameVerdict.badChars;
  if (name.split(' ').length > 2) return NameVerdict.tooManyWords;

  // 🔴 ตรวจคำหยาบ**หลังยุบช่องว่าง** เพราะ "เ ห ี้ ย" ต้องไม่รอด
  final flat = name.replaceAll(' ', '').toLowerCase();
  for (final bad in _rude) {
    if (flat.contains(bad)) return NameVerdict.rude;
  }

  if (!_hasBody.hasMatch(name)) return NameVerdict.notPronounceable;
  if (_startsWithMark.hasMatch(name)) return NameVerdict.notPronounceable;

  // "อออออ" หรือ "aaaa" — มีตัวอักษรจริงแต่ไม่ใช่ชื่อ
  final distinct = flat.split('').toSet().length;
  if (distinct < 2) return NameVerdict.notPronounceable;

  return NameVerdict.ok;
}
